/**
 * report.ts — renders an EvalReport to a human-readable Markdown string.
 * EVAL-ONLY.
 */

import type { Bucket, CaseResult, EvalReport } from './evaluator'
import { EU_EEA } from './regions'

function pct(b: Bucket): string {
  return `${(b.recall * 100).toFixed(1)}% (${b.hits}/${b.total})`
}

function sortedCountryRows(
  byCountry: Record<string, Bucket>,
  filter: (c: string) => boolean,
): string[] {
  return Object.entries(byCountry)
    .filter(([c]) => filter(c))
    .sort((a, b) => a[1].recall - b[1].recall || a[0].localeCompare(b[0]))
    .map(([c, b]) => `| ${c} | ${pct(b)} |`)
}

function missExamples(misses: CaseResult[], limit: number): string[] {
  // One representative miss per country (the first), then cap.
  const perCountry = new Map<string, CaseResult>()
  for (const m of misses) if (!perCountry.has(m.country)) perCountry.set(m.country, m)
  return [...perCountry.values()]
    .slice(0, limit)
    .map(
      (m) =>
        `| ${m.country} | \`${m.phone}\` | ${m.format} |`,
    )
}

export function renderMarkdown(r: EvalReport): string {
  const euMissCountries = new Set(
    r.misses.filter((m) => m.region === 'EU_EEA').map((m) => m.country),
  )
  const euFullyMissed = [...euMissCountries].filter((c) => {
    const b = r.byCountry[c]
    return b && b.hits === 0
  })

  return `# Phone-regex accuracy eval — Recode-IT

> EVAL-ONLY artifact. Generated by \`npx vitest run src/engine/__tests__/phone_eval\`.
> Ground truth: \`libphonenumber-js\` (MIT, devDependency) mobile example numbers.
> Measures the PRODUCTION regex (\`PHONE_IT_PREFIX_RE\` + \`PHONE_IT_MOBILE_RE\`
> in \`src/engine/regex.ts\`) via \`applyRegexRules\`. Nothing here ships.

- Generated: ${r.generatedAt}
- Corpus size: ${r.corpusSize} rendered phone strings
- Countries: ${Object.keys(r.byCountry).length} (EU/EEA + world sample)

## Headline

| Scope | Recall |
| --- | --- |
| **GLOBAL** | **${pct(r.global)}** |
| EU/EEA | ${pct(r.byRegion.EU_EEA)} |
| World sample | ${pct(r.byRegion.WORLD_SAMPLE)} |

## Recall by format

| Format | Recall |
| --- | --- |
${Object.entries(r.byFormat)
  .sort((a, b) => b[1].recall - a[1].recall)
  .map(([f, b]) => `| ${f} | ${pct(b)} |`)
  .join('\n')}

## Recall by country — EU/EEA (mandatory surface)

| Country | Recall |
| --- | --- |
${sortedCountryRows(r.byCountry, (c) => EU_EEA.includes(c)).join('\n')}

## Recall by country — world sample

| Country | Recall |
| --- | --- |
${sortedCountryRows(r.byCountry, (c) => !EU_EEA.includes(c)).join('\n')}

## Countries with ZERO recall

${
  euFullyMissed.length === 0 && Object.values(r.byCountry).every((b) => b.hits > 0)
    ? '_None._'
    : Object.entries(r.byCountry)
        .filter(([, b]) => b.hits === 0)
        .map(([c]) => `- ${c} (${EU_EEA.includes(c) ? 'EU/EEA' : 'world'})`)
        .join('\n') || '_None._'
}

## Concrete misses (one per country, capped)

| Country | Phone (not caught) | Format |
| --- | --- | --- |
${missExamples(r.misses, 40).join('\n')}

## False positives (PHONE-category hits on non-phone tokens)

- Probes: ${r.fp.total}
- Clean (no false PHONE hit): ${r.fp.clean}/${r.fp.total}

${
  r.fp.falsePositives.length === 0
    ? '_No false positives._'
    : '| Probe | Text | False PHONE match |\n| --- | --- | --- |\n' +
      r.fp.falsePositives
        .map(
          (fp) =>
            `| ${fp.label} | \`${fp.text}\` | ${fp.falseMatches
              .map((m) => `\`${m}\``)
              .join(', ')} |`,
        )
        .join('\n')
}

---
*Re-run to regenerate. Determinism: corpus is derived from fixed library
metadata + fixed render rules, so output is stable across runs (modulo the
\`generatedAt\` timestamp).*
`
}
